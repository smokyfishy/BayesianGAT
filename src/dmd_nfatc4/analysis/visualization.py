"""Static figures (matplotlib, headless) and structure-viewer scripts (PyMOL / py3Dmol).

Residue selections are always written with **1-based UniProt/PDB numbering**
(``resi = index0 + 1``), validated against the structure beforehand. Neither PyMOL nor
py3Dmol is a dependency: ``.pml`` files are plain text and the HTML viewer loads
3Dmol.js from a CDN when opened in a browser.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

PALETTE = ["#d62728", "#ff7f0e", "#bcbd22", "#2ca02c", "#17becf", "#1f77b4", "#9467bd", "#8c564b"]


def plot_joint_score(raw, smoothed, threshold, clusters_df, out: Path, title_suffix="") -> Path:
    x = np.arange(1, len(smoothed) + 1)
    fig, ax = plt.subplots(figsize=(14, 4))
    ax.plot(x, raw, color="0.8", lw=0.8, label="raw joint score")
    ax.plot(x, smoothed, color="#1f3b73", lw=1.4, label="smoothed (sigma=2)")
    ax.axhline(threshold, color="0.4", ls="--", lw=1, label="93rd percentile")
    for k, row in clusters_df.iterrows():
        ax.axvspan(row.Start_uniprot - 0.5, row.End_uniprot + 0.5, color=PALETTE[k % len(PALETTE)], alpha=0.25)
    ax.set_xlabel("UniProt Q14934 residue (1-based)")
    ax.set_ylabel("saliency x MC std x delta-hidden")
    ax.set_title(f"NFATC4 legacy joint score{title_suffix} (exploratory; model trained on leaked simulated labels)")
    ax.set_xlim(1, len(smoothed))
    ax.legend(loc="upper right", frameon=False)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=200)
    plt.close(fig)
    return out


def plot_signals(signals: dict[str, np.ndarray], flags: np.ndarray | None, out: Path) -> Path:
    n = len(next(iter(signals.values())))
    x = np.arange(1, n + 1)
    fig, axes = plt.subplots(len(signals) + (flags is not None), 1, figsize=(14, 1.8 * (len(signals) + 1)), sharex=True)
    axes = np.atleast_1d(axes)
    i = 0
    if flags is not None:
        axes[0].fill_between(x, flags, step="mid", color="#d62728", alpha=0.6)
        axes[0].set_ylabel("simulated\nflag")
        i = 1
    for (name, sig), ax in zip(signals.items(), axes[i:]):
        ax.plot(x, sig, lw=0.9, color="#1f3b73")
        ax.set_ylabel(name)
    axes[-1].set_xlabel("UniProt Q14934 residue (1-based)")
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=200)
    plt.close(fig)
    return out


def _resi_ranges(windows_uniprot):
    return "+".join(f"{s}-{e}" for s, e in windows_uniprot)


def write_pml(pdb_path: Path, windows_uniprot: list[tuple[int, int]], out: Path, png_name: str | None = None) -> Path:
    lines = [
        "# Auto-generated by dmd_nfatc4 visualize-nfatc4. Residue numbers are 1-based UniProt/PDB.",
        "# Windows are exploratory outputs of the legacy model; not validated functional sites.",
        f"load {Path(pdb_path).as_posix()}, NFATC4",
        "hide everything, NFATC4",
        "show cartoon, NFATC4",
        "color gray80, NFATC4",
        "spectrum b, red_orange_yellow_cyan_blue, NFATC4 and name CA, minimum=50, maximum=90",
        "color gray80, NFATC4",
    ]
    for k, (s, e) in enumerate(windows_uniprot, start=1):
        lines += [
            f"select win{k}, NFATC4 and resi {s}-{e}",
            f"show sticks, win{k}",
            f"color {['red', 'orange', 'yellow', 'green', 'cyan', 'blue', 'magenta', 'salmon'][(k - 1) % 8]}, win{k}",
        ]
    lines += ["orient NFATC4", "set ray_opaque_background, off"]
    if png_name:
        lines += ["ray 1600,1200", f"png {png_name}, dpi=300"]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def write_py3dmol_html(pdb_path: Path, windows_uniprot: list[tuple[int, int]], out: Path) -> Path:
    pdb_text = Path(pdb_path).read_text(encoding="utf-8")
    styles = [
        {"resi": f"{s}-{e}", "color": ["red", "orange", "yellow", "green", "cyan", "blue", "magenta"][k % 7]}
        for k, (s, e) in enumerate(windows_uniprot)
    ]
    html = f"""<!doctype html><html><head><meta charset="utf-8"><title>NFATC4 windows</title>
<script src="https://3Dmol.org/build/3Dmol-min.js"></script></head><body>
<p>NFATC4 (AF-Q14934-F1 v4). Highlighted: exploratory windows (1-based UniProt numbering). Not validated sites.</p>
<div id="v" style="width:900px;height:650px;position:relative"></div>
<script>
const pdb = {json.dumps(pdb_text)};
const v = $3Dmol.createViewer("v", {{backgroundColor: "white"}});
v.addModel(pdb, "pdb");
v.setStyle({{}}, {{cartoon: {{color: "lightgrey"}}}});
for (const s of {json.dumps(styles)}) {{
  v.addStyle({{chain: "A", resi: s.resi}}, {{cartoon: {{color: s.color}}, stick: {{color: s.color}}}});
}}
v.zoomTo(); v.render();
</script></body></html>"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    return out
